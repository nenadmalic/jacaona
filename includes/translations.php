/**
 * Get translation for a key
 * @param string $key Translation key
 * @param string $lang Language code (default: 'hr')
 * @return string Translated text or key if not found
 */
function t($key, $lang = 'hr') {
    global $translations;
    if (isset($translations[$lang][$key])) {
        return $translations[$lang][$key];
    }
    // Fallback to Croatian if translation not found
    if (isset($translations['hr'][$key])) {
        return $translations['hr'][$key];
    }
    // Return key if no translation found
    return $key;
}
